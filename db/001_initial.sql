CREATE TABLE IF NOT EXISTS users (
 id INT UNSIGNED PRIMARY KEY AUTO_INCREMENT, username VARCHAR(64) NOT NULL UNIQUE,
 email VARCHAR(254) NULL UNIQUE, full_name VARCHAR(150) NOT NULL, password_hash VARCHAR(255) NOT NULL,
 role VARCHAR(20) NOT NULL DEFAULT 'USER', created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 CHECK(role IN ('USER','ADMIN'))
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS books (
 id INT UNSIGNED PRIMARY KEY AUTO_INCREMENT, book_code VARCHAR(50) NOT NULL UNIQUE,
 title VARCHAR(255) NOT NULL, author VARCHAR(255) NOT NULL, category VARCHAR(100) NULL,
 description TEXT NULL, total_quantity INT NOT NULL DEFAULT 0, available_quantity INT NOT NULL DEFAULT 0,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 CHECK(total_quantity>=0), CHECK(available_quantity>=0 AND available_quantity<=total_quantity),
 INDEX(title), INDEX(author), INDEX(category)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS borrow_requests (
 id INT UNSIGNED PRIMARY KEY AUTO_INCREMENT, user_id INT UNSIGNED NOT NULL, book_id INT UNSIGNED NOT NULL,
 borrow_date DATE NOT NULL, due_date DATE NOT NULL, status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
 reviewed_by INT UNSIGNED NULL, reviewed_at TIMESTAMP NULL, decision_note VARCHAR(500) NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 CHECK(due_date>borrow_date), CHECK(status IN ('PENDING','APPROVED','DENIED')),
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE RESTRICT,
 FOREIGN KEY(book_id) REFERENCES books(id) ON DELETE RESTRICT,
 FOREIGN KEY(reviewed_by) REFERENCES users(id) ON DELETE SET NULL,
 INDEX(user_id,created_at), INDEX(status,created_at), INDEX(book_id,status)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS sessions (
 token_hash CHAR(64) PRIMARY KEY, user_id INT UNSIGNED NOT NULL,
 expires_at DATETIME NOT NULL, FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE, INDEX(expires_at)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS audit_logs (
 id INT UNSIGNED PRIMARY KEY AUTO_INCREMENT, actor_user_id INT UNSIGNED NULL,
 event_type VARCHAR(100) NOT NULL, entity_type VARCHAR(50) NULL, entity_id VARCHAR(100) NULL,
 request_id VARCHAR(100) NOT NULL, details JSON NULL, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(actor_user_id) REFERENCES users(id) ON DELETE SET NULL,
 INDEX(actor_user_id,created_at), INDEX(event_type,created_at), INDEX(request_id)
) ENGINE=InnoDB;
